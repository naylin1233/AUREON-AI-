import assert from 'node:assert/strict';
import { addSecondsToTimestamp, parseSubtitleFile, serializeSubtitles } from '../src/subtitles.ts';

const srt='1\n00:00:01,000 --> 00:00:03,500\nမင်္ဂလာပါ။\n\n2\n00:00:04,000 --> 00:00:06,000\nနောက်တစ်ခန်းကို ကြည့်ကြရအောင်။';
const myanmar=parseSubtitleFile(srt,'myanmar');
assert.equal(myanmar.length,2);
assert.equal(myanmar[0].start,'00:00:01,000');
assert.equal(myanmar[0].myanmar,'မင်္ဂလာပါ။');
assert.equal(myanmar[0].english,'');
const vtt='WEBVTT\n\n00:01.250 --> 00:03.000 align:start\nHello there.\n\n00:04.000 --> 00:06.000\nNext scene.';
const english=parseSubtitleFile(vtt,'english');
assert.equal(english.length,2);
assert.equal(english[0].start,'00:00:01,250');
assert.equal(english[0].english,'Hello there.');
const merged=[{...myanmar[0],english:english[0].english}];
const exportedSrt=serializeSubtitles(merged,'myanmar','srt');
assert.match(exportedSrt,/00:00:01,000 -->/);
assert.match(serializeSubtitles(merged,'english','vtt'),/^WEBVTT\n\n/);
assert.equal(addSecondsToTimestamp('00:00:58,500',3),'00:01:01,500');
assert.throws(()=>parseSubtitleFile('1\n00:00:04,000 --> 00:00:02,000\nBad range'),/later than start/);
console.log('AUREON subtitle smoke test passed: SRT/VTT import, Myanmar/English tracks, timestamps and export.');
